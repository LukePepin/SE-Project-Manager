"""Write a committed, redacted trace table from a git-ignored elicitation record (audit 10/9, M6).

Status: PROPOSED (AI-drafted by Claude on 2026-10-09, D-044).

Elicitation records stay out of git (D-035), so a clone can't check that a requirement traces to Luke's
words. This writes `trace_items.md` beside the SE documents. It has two parts:
  1. every E-id with its type, basis and status, and its statement with private terms replaced by
     [private] (terms from the project's .privacy-terms and Luke's global list) and cut to 120 characters;
  2. the reconciliation: each live or deferred requirement in SE-03 with the E-ids its Trace column cites,
     and a verdict: "traced" (cites a stated item), "decision only" (cites a D-nnn but no stated item)
     or "Claude's" (marked so, or cites neither).

Usage:
  python trace_table.py RECORD_FOLDER SE03_FILE OUT_FILE [--terms FILE ...]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def load_terms(files: list[Path]) -> list[str]:
    terms = []
    for f in files:
        if f.exists():
            for line in f.read_text(encoding="utf-8").splitlines():
                t = line.split("  #")[0].strip()
                if t and not t.startswith("#"):
                    terms.append(t)
    return sorted(terms, key=len, reverse=True)


def redact(text: str, terms: list[str]) -> str:
    for t in terms:
        text = re.sub(re.escape(t), "[private]", text, flags=re.I)
    return text if len(text) <= 120 else text[:117] + "..."


def items(record: Path) -> list[list[str]]:
    out = []
    for line in (record / "items.md").read_text(encoding="utf-8").splitlines():
        if re.match(r"^\| E-\d+ \|", line):
            c = [x.strip() for x in line.strip().strip("|").split("|")]
            out.append([c[0], c[1], "|".join(c[2:-4]).strip(), c[-3], c[-1]])
    return out


def requirements(se03: Path) -> list[tuple[str, str, str]]:
    """(id, trace column, status) for live and deferred requirements."""
    out = []
    for line in se03.read_text(encoding="utf-8").splitlines():
        if not re.match(r"^\| [A-Z]+-\d+[a-zW]? \| [A-Z`/]", line) or re.match(r"^\| (I|T|DM)-\d", line):
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        trace = c[3] if len(c) == 7 else c[2]
        out.append((c[0], trace, c[-1]))
    return out


def verdict(trace: str, basis: dict[str, str]) -> str:
    if "Claude's" in trace:
        return "Claude's"
    eids = re.findall(r"E-\d+", trace)
    if any(basis.get(e) == "stated" for e in eids):
        return "traced"
    if re.search(r"D-\d+", trace):
        return "decision only"
    return "Claude's"


def build(record: Path, se03: Path, terms: list[str]) -> str:
    its = items(record)
    basis = {i[0]: i[3] for i in its}
    reqs = requirements(se03)
    verdicts = [(r, verdict(t, basis), t) for r, t, _ in reqs]
    counts = {v: sum(1 for _, x, _ in verdicts if x == v) for v in ("traced", "decision only", "Claude's")}
    claudes = counts["Claude's"]
    req_rows = ["| %s | %s | %s |" % (r, v, ", ".join(re.findall(r"E-\d+", t)) or "—") for r, v, t in verdicts]
    item_rows = ["| %s | %s | %s | %s | %s |" % (i[0], i[1], i[3], redact(i[4], terms), redact(i[2], terms).replace("|", "/"))
                 for i in its]
    out = [
        "# Trace items (redacted)",
        "",
        f"**Status: DRAFT.** Generated by `.claude/skills/elicit/trace_table.py` from the git-ignored record"
        f" `{record.name}` and `{se03.name}`. Private terms are replaced by [private]; statements are cut at"
        " 120 characters. Regenerate after the record or SE-03 changes.",
        "",
        "## Reconciliation of SE-03",
        "",
        f"{len(verdicts)} live or deferred requirements: {counts['traced']} traced to Luke's stated words,"
        f" {counts['decision only']} resting on a decision only, {claudes} Claude's.",
        "",
        "| Requirement | Verdict | E-ids cited |",
        "|---|---|---|",
        *req_rows,
        "",
        "## Items",
        "",
        "| ID | Type | Basis | Status | Statement (redacted) |",
        "|---|---|---|---|---|",
        *item_rows,
    ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("record", type=Path)
    p.add_argument("se03", type=Path)
    p.add_argument("out", type=Path)
    p.add_argument("--terms", type=Path, nargs="*", default=[])
    args = p.parse_args(argv)
    args.out.write_text(build(args.record, args.se03, load_terms(args.terms)), encoding="utf-8")
    print(f"Wrote {args.out}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
