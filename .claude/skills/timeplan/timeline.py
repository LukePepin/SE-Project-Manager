"""Propose a project's gate dates and calendar blocks, without writing to any service (TL-01, TL-02, INT-01, INT-02).

Status: PROPOSED (AI-drafted by Claude on 2026-10-08 from Luke's direction, D-015 and D-018;
not reviewed by Luke). The gate shares are Claude's proposals.

From the budget H (Luke's, after the time suggestion) and Luke's hours per week, each gate gets a
share of H and a date: start + (hours so far / hours per week) weeks. The script writes files only:
  timeline.md    the proposal, marked PROPOSED, with a Todoist checklist and, with --github, the
                 `gh` commands for milestones (all run only after Luke approves)
  timeline.ics   all-day gate events, plus weekly deep-work blocks with --block (import into Calendar)
It imports no network module: nothing reaches Todoist, Calendar or GitHub from here.

Usage:
  python timeline.py --hours 12 --per-week 4 --start 2026-10-12 --tier short
                     [--block SAT@10:00] [--github owner/repo] [--project NAME] [--out-dir DIR]
"""

from __future__ import annotations

import argparse
import math
import sys
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

GATES = {
    "immediate": [("Done", 1.0)],
    "short": [("G0 Charter", 0.10), ("G1 First increment", 0.45), ("G2 Usable", 0.30), ("G3 Closeout", 0.15)],
    "long": [("G0 Charter", 0.05), ("G1 Design", 0.20), ("G2 First increment", 0.30), ("G3 Verified", 0.30),
             ("G4 Closeout", 0.15)],
}
DAYS = {"MON": 0, "TUE": 1, "WED": 2, "THU": 3, "FRI": 4, "SAT": 5, "SUN": 6}


@dataclass
class Gate:
    name: str
    hours: float
    cumulative: float
    due: date


def plan(hours: float, per_week: float, start: date, tier: str) -> list[Gate]:
    if hours <= 0 or per_week <= 0:
        raise ValueError("hours and hours per week must be positive")
    gates, cum = [], 0.0
    for name, share in GATES[tier]:
        cum += hours * share
        gates.append(Gate(name, hours * share, cum, start + timedelta(days=math.ceil(cum / per_week * 7))))
    return gates


def blocks(hours: float, per_week: float, start: date, spec: str) -> list[tuple[datetime, float]]:
    """Weekly blocks of up to `per_week` hours on DAY@HH:MM until `hours` are covered."""
    day, hhmm = spec.upper().split("@")
    h, m = (int(x) for x in hhmm.split(":"))
    first = start + timedelta(days=(DAYS[day] - start.weekday()) % 7)
    out, left, k = [], hours, 0
    while left > 1e-9:
        length = min(per_week, left)
        out.append((datetime(first.year, first.month, first.day, h, m) + timedelta(weeks=k), length))
        left -= length
        k += 1
    return out


def ics(project: str, gates: list[Gate], blks: list[tuple[datetime, float]]) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Games-People-Play//timeplan//EN", "CALSCALE:GREGORIAN"]
    for i, g in enumerate(gates):
        lines += ["BEGIN:VEVENT", f"UID:{project}-gate-{i}@games-people-play", f"DTSTAMP:{stamp}",
                  f"DTSTART;VALUE=DATE:{g.due:%Y%m%d}", f"DTEND;VALUE=DATE:{g.due + timedelta(days=1):%Y%m%d}",
                  f"SUMMARY:{project}: {g.name} (proposed)", "END:VEVENT"]
    for i, (when, length) in enumerate(blks):
        mins = round(length * 60)
        lines += ["BEGIN:VEVENT", f"UID:{project}-block-{i}@games-people-play", f"DTSTAMP:{stamp}",
                  f"DTSTART:{when:%Y%m%dT%H%M%S}", f"DURATION:PT{mins // 60}H{mins % 60}M",
                  f"SUMMARY:{project}: deep work", "END:VEVENT"]
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def render(project: str, args, gates: list[Gate], blks) -> str:
    out = [
        f"# Proposed timeline: {project}",
        "",
        "**Status: PROPOSED.** Generated by `timeline.py`. Nothing here is in Todoist, Calendar or GitHub."
        " Each entry goes in only after Luke approves it in the session (TL-02, SAFE-05).",
        "",
        f"Budget {args.hours:g} h (Luke's, TIME-02) at {args.per_week:g} h/week from {args.start}, tier {args.tier}.",
        "",
        "| Gate | Hours | Hours so far | Proposed date |",
        "|---|---|---|---|",
        *[f"| {g.name} | {g.hours:.1f} | {g.cumulative:.1f} | {g.due:%a %Y-%m-%d} |" for g in gates],
        "",
        "## Todoist checklist (paste after approving)",
        "",
        *[f"- [ ] {project}: {g.name} (due {g.due:%Y-%m-%d})" for g in gates],
        f"- [ ] {project}: monthly maintenance check (every month)",
    ]
    if blks:
        out += ["", f"## Calendar blocks ({len(blks)}, in timeline.ics)", "",
                *[f"- {w:%a %Y-%m-%d %H:%M}, {length:g} h" for w, length in blks]]
    if args.github:
        out += ["", "## GitHub milestones (run only after approving)", "", "```"]
        out += [f"gh api repos/{args.github}/milestones -f title='{g.name}' -f due_on='{g.due:%Y-%m-%d}T23:59:59Z'"
                for g in gates]
        out += ["```"]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--hours", type=float, required=True, help="Luke's budget in hours")
    p.add_argument("--per-week", type=float, required=True, help="hours per week Luke can give it")
    p.add_argument("--start", type=date.fromisoformat, required=True)
    p.add_argument("--tier", choices=sorted(GATES), required=True)
    p.add_argument("--project", default="project")
    p.add_argument("--block", help="weekly deep-work block start, e.g. SAT@10:00")
    p.add_argument("--github", help="owner/repo, to print milestone commands")
    p.add_argument("--out-dir", type=Path, default=Path("."))
    args = p.parse_args(argv)

    gates = plan(args.hours, args.per_week, args.start, args.tier)
    blks = blocks(args.hours, args.per_week, args.start, args.block) if args.block else []
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "timeline.md").write_text(render(args.project, args, gates, blks) + "\n", encoding="utf-8")
    (args.out_dir / "timeline.ics").write_text(ics(args.project, gates, blks), encoding="utf-8", newline="")
    print(f"Wrote {args.out_dir / 'timeline.md'} and {args.out_dir / 'timeline.ics'} (proposals only).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
