"""Suggest how many hours a project deserves, and learn from actual hours (TIME-01 to TIME-03).

Status: PROPOSED (AI-drafted by Claude on 2026-10-08 from Luke's direction, D-015 and D-017;
not reviewed by Luke). The constants are Claude's proposals and are meant to be corrected
by calibration.

Luke's inputs (E-042: "Project purpose, length, complexity, my availability"):
  purpose p       1-5, how much the outcome matters
  length L        hours of plain doing, or a class: tiny 1, small 4, medium 16, large 64
  complexity k    1-5, how much is unknown or fiddly
  availability a  hours per week Luke can give it

Model (hours only, D-017):
  need   = L * COMPLEXITY[k] * calibration          hours to get the basic result
  r      = PURPOSE[p]                               the outcome is worth r times its basic need
  c      = max(1, REF_AVAILABILITY / a)             an hour costs more when hours are scarce
  V(h)   = r * need * (1 - exp(-h / need))          value of h hours: diminishing returns
  best h where V'(h) = c, i.e. r * exp(-h / need) = c:
  h*     = need * ln(r / c)   if r > c, else 0      (0 means not worth starting)

Verdict: h* = 0 is no-go; h* < need / 2 is shrink (do a smaller version); otherwise go.
Tier (D-006): h* under 4 h is immediate, under 40 h short, otherwise long.
Calibration (TIME-03): the median of actual/suggested over recorded projects multiplies `need`.

Usage:
  python time_equation.py suggest --purpose 3 --length small --complexity 2 --availability 4
  python time_equation.py record --project attic --suggested 5 --actual 3.5
"""

from __future__ import annotations

import argparse
import csv
import math
import statistics
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path

COMPLEXITY = {1: 1.0, 2: 1.25, 3: 1.6, 4: 2.0, 5: 2.5}
PURPOSE = {1: 1.0, 2: 1.5, 3: 2.5, 4: 4.0, 5: 7.0}
LENGTH_CLASS = {"tiny": 1.0, "small": 4.0, "medium": 16.0, "large": 64.0}
REF_AVAILABILITY = 5.0  # hours per week at which an hour costs one hour
DEFAULT_CALIBRATION = Path(__file__).resolve().parent / "calibration.csv"
FIELDS = ["date", "project", "stage", "suggested", "actual"]


@dataclass
class Suggestion:
    need: float
    worth_ratio: float
    hour_cost: float
    hours: float
    verdict: str
    tier: str
    weeks: float
    calibration: float
    calibration_n: int


def parse_length(value: str) -> float:
    v = value.strip().lower()
    if v in LENGTH_CLASS:
        return LENGTH_CLASS[v]
    hours = float(v)
    if hours <= 0:
        raise ValueError("length must be positive")
    return hours


def load_calibration(path: Path) -> tuple[float, int]:
    if not path.exists():
        return 1.0, 0
    with open(path, newline="", encoding="utf-8") as f:
        ratios = [float(r["actual"]) / float(r["suggested"]) for r in csv.DictReader(f) if float(r["suggested"]) > 0]
    return (statistics.median(ratios), len(ratios)) if ratios else (1.0, 0)


def suggest(purpose: int, length: float, complexity: int, availability: float, calibration: float = 1.0,
            calibration_n: int = 0) -> Suggestion:
    if purpose not in PURPOSE or complexity not in COMPLEXITY:
        raise ValueError("purpose and complexity are 1 to 5")
    if availability <= 0:
        raise ValueError("availability must be positive hours per week")
    need = length * COMPLEXITY[complexity] * calibration
    r = PURPOSE[purpose]
    c = max(1.0, REF_AVAILABILITY / availability)
    hours = need * math.log(r / c) if r > c else 0.0
    verdict = "no-go" if hours <= 0 else "shrink" if hours < need / 2 else "go"
    tier = "immediate" if hours < 4 else "short" if hours < 40 else "long"
    return Suggestion(need, r, c, hours, verdict, tier, hours / availability, calibration, calibration_n)


def record(path: Path, project: str, suggested: float, actual: float, when: str | None = None,
           stage: str = "closeout") -> dict:
    """Append one project's hours for a gate or its closeout; return the error (TIME-03)."""
    new = not path.exists()
    with open(path, "a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        if new:
            w.writeheader()
        w.writerow({"date": when or date.today().isoformat(), "project": project, "stage": stage,
                    "suggested": f"{suggested:g}", "actual": f"{actual:g}"})
    factor, n = load_calibration(path)
    return {"error_hours": actual - suggested, "ratio": actual / suggested if suggested else math.inf,
            "calibration": factor, "n": n}


def render(args, s: Suggestion) -> str:
    return "\n".join([
        "# Time suggestion",
        "",
        "**Status: PROPOSED.** Generated by `time_equation.py`. This is advice: Luke sets the budget,"
        " and the record keeps both numbers (TIME-02).",
        "",
        f"Inputs: purpose {args.purpose}, length {args.length} ({s.need / COMPLEXITY[args.complexity] / s.calibration:g} h"
        f" of doing), complexity {args.complexity}, availability {args.availability:g} h/week.",
        "",
        "| Step | Value |",
        "|---|---|",
        f"| need = length x complexity factor x calibration | {s.need:.1f} h (calibration {s.calibration:.2f},"
        f" from {s.calibration_n} closed projects) |",
        f"| worth ratio r (purpose) | {s.worth_ratio:g} |",
        f"| hour cost c = max(1, {REF_AVAILABILITY:g} / availability) | {s.hour_cost:.2f} |",
        f"| **suggested hours h\\* = need x ln(r / c)** | **{s.hours:.1f} h** |",
        f"| verdict | **{s.verdict}** |",
        f"| tier | {s.tier} |",
        f"| at {args.availability:g} h/week | {s.weeks:.1f} weeks |",
        "",
        "A no-go means the outcome is not worth an hour at Luke's current availability."
        " A shrink means the project is worth doing, but less than its basic need: cut it down first.",
    ])


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("suggest")
    s.add_argument("--purpose", type=int, required=True)
    s.add_argument("--length", required=True, help="hours of doing, or tiny/small/medium/large")
    s.add_argument("--complexity", type=int, required=True)
    s.add_argument("--availability", type=float, required=True, help="hours per week")
    s.add_argument("--calibration", type=Path, default=DEFAULT_CALIBRATION)
    s.add_argument("--out")
    r = sub.add_parser("record")
    r.add_argument("--project", required=True)
    r.add_argument("--stage", default="closeout", help="a gate (G0, G1, ...) or closeout")
    r.add_argument("--suggested", type=float, required=True)
    r.add_argument("--actual", type=float, required=True)
    r.add_argument("--calibration", type=Path, default=DEFAULT_CALIBRATION)
    args = p.parse_args(argv)

    if args.cmd == "record":
        res = record(args.calibration, args.project, args.suggested, args.actual, stage=args.stage)
        print(f"Recorded {args.project} ({args.stage}): actual {args.actual:g} h vs suggested {args.suggested:g} h"
              f" (error {res['error_hours']:+g} h, ratio {res['ratio']:.2f}). Calibration is now"
              f" {res['calibration']:.2f} from {res['n']} projects.")
        return 0
    factor, n = load_calibration(args.calibration)
    sug = suggest(args.purpose, parse_length(args.length), args.complexity, args.availability, factor, n)
    report = render(args, sug)
    if args.out:
        Path(args.out).write_text(report + "\n", encoding="utf-8")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
